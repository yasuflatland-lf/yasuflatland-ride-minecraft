"""Measured scooter dimensions in model pixels, before the final x mirror."""

import math

I2M_SCALE = 0.0498
I2M_ORIGIN_X = 425
I2M_ORIGIN_Y = 537
WHEELBASE = 23.6
FRONT_AXLE_Z = -WHEELBASE / 2
REAR_AXLE_Z = WHEELBASE / 2
TYRE_RADIUS = 4.3
AXLE_Y = TYRE_RADIUS
TYRE_HALF_WIDTH = 1.05
STEERING_AXIS_DEGREES = 20.9
HEADSET_Y = 17.9
SEAT_Y = 16.1
DRIVER_SEAT_Z = 3.5
PASSENGER_SEAT_Z = 9.5
STAND_PIVOT = (0, 5.0, 2.0)

PLACEHOLDER_BODY_HALF_WIDTH = 4.0
PLACEHOLDER_BODY_BOTTOM_Y = 5.5
PLACEHOLDER_BODY_TOP_Y = 15.0
PLACEHOLDER_BODY_FRONT_Z = -8.0
PLACEHOLDER_BODY_REAR_Z = 16.0
PLACEHOLDER_COLUMN_SIZE = 0.8
PLACEHOLDER_HEADLIGHT_LO = (-1.2, 18.5, -8.0)
PLACEHOLDER_HEADLIGHT_HI = (1.2, 20.5, -6.5)
PLACEHOLDER_TAIL_LIGHT_LO = (-0.8, 12.5, 17.0)
PLACEHOLDER_TAIL_LIGHT_HI = (0.8, 14.5, 18.0)
PLACEHOLDER_STAND_LO = (-2.0, 0, 1.5)
PLACEHOLDER_STAND_HI = (2.0, STAND_PIVOT[1], 2.5)
VISIBLE_BOUNDS_WIDTH = 3
VISIBLE_BOUNDS_HEIGHT = 2.5
VISIBLE_BOUNDS_OFFSET = (0, 1, 0)
# Raised from 3500 for 40-segment tyres, which keep the tread silhouette within 0.015 units of a circle.
CUBE_BUDGET = 3650
CUBE_BUDGET_CEILING = 3800


def i2m(xi, yi) -> tuple[float, float]:
    return ((I2M_ORIGIN_X - xi) * I2M_SCALE, (I2M_ORIGIN_Y - yi) * I2M_SCALE)


def steering_axis_z(y):
    return FRONT_AXLE_Z + (y - AXLE_Y) * math.tan(math.radians(STEERING_AXIS_DEGREES))


STEER_PIVOT = (0, HEADSET_Y, steering_axis_z(HEADSET_Y))
